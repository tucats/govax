package rtl

// p1VectorEntry is one fixed VAX/VMS system-service-vector address, matching
// p1_vector.c's struct P1_VECTOR array. These addresses are architected VMS
// constants (the well-known P1-space system-service vector region), not
// something this port gets to choose — a real compiled VMS program's CALLS/
// JMP instruction targets one of them directly. Phase 13 (docs/PHASE-13.md)
// is responsible for actually writing the XFC$P1VECTOR trampoline bytes at
// these addresses as part of microkernel bootstrap (p1_vector.c's own
// p1_init); this phase only needs the address-to-name table to dispatch a
// call once one of these addresses is reached (see Environment.SystemService
// in service.go), whether that's driven by a real CALLS through Phase 13's
// bootstrap or directly in a test.
type p1VectorEntry struct {
	Name string
	Addr uint32
	// Jmp is true only for SYS$SRCHANDLER, matching p1_vector.c's own
	// comment: reached via JMP rather than CALL, so call_service's match is
	// against Addr-2 (the XFC opcode sits two bytes earlier than a CALL
	// target, which always has a 2-byte procedure-entry mask first).
	Jmp bool
}


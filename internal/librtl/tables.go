package librtl

// LIBRTL's data tables (docs/PHASE-54, "Data entries"). The first 768
// bytes of LIBRTL.EXE's transfer vector aren't routines but three
// 256-byte translation tables, which a program addresses directly, most
// often as a translation table for MOVTC (LIB$MOVTC's descriptor, or the
// instruction itself):
//
//	MOVTC  LEN,SRC,#^A" ",G^LIB$AB_UPCASE,LEN,DST
//
// Byte n of a table is what character n translates to. govax copies each
// table into system space with the stubs (machine.EnsureShims), where
// every mode may read it and none but kernel may write it, and defines
// its SHIM$LIBRTL_<offset> symbol (and its own name) there.

// Table is one of LIBRTL's data tables.
type Table struct {
	// Name is the table's universal symbol, e.g. "LIB$AB_UPCASE"; its
	// offset in the transfer vector is vmsdef.ImageSymbols'.
	Name string

	// Data is the table's contents.
	Data *[256]byte
}

// Tables are LIBRTL's data tables. LIBRTL2.EXE has eleven more (the
// manual's MOVTC entry), which govax doesn't provide.

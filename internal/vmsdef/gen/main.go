// Command gen parses reference/vms/{fabdef,rabdef,rmsdef}.h and emits
// internal/vmsdef/constants_generated.go: a flat map of every real FAB$/
// RAB$/RMS$_ symbolic-constant name to its numeric value (Constants), plus
// further maps from other real VMS 7.3 sources: LNMConstants from
// reference/vms/lnmdef.sdl (SDL source; see sdl.go) and SSConstants from
// reference/vms/ssdef.txt (a BLISS LITERAL listing; see bliss.go), both
// docs/PHASE-25.md, and DEVConstants and JPIConstants from
// reference/vms/devdef.sdl and jpidef.sdl (docs/PHASE-26.md). The
// message texts of reference/vms/sysmsg.txt go to a second file,
// messages_generated.go (msg.go). They are kept as separate maps, not merged into
// Constants, because .RMSDEF (internal/asm) defines every Constants entry
// as an assembler symbol and must not start defining LNM$/SS$/DEV$/JPI$
// names too. Run via `go
// generate` from internal/vmsdef (see the go:generate directive in
// constants.go) rather than hand-transcribing ~450 #define lines — see
// docs/PHASE-24.md's design notes on why (the same reasoning
// internal/cpu/gen/main.go already established for instruction_table.h's
// own ~284-entry table).
//
// The three headers only ever define a value constant as a plain, bare
// integer literal (decimal or 0x-prefixed hex) — never an expression
// combining other macros — so a single-line regex per #define is
// sufficient; no C preprocessor/expression evaluation is needed. Each
// header also ends with a block of C-only field-access aliasing macros
// (e.g. "#define fab$w_ifi fab$r_ifi_overlay.fab$w_ifi") that this parser
// must not mistake for value constants — conveniently, every real value
// constant is spelled in upper case (FAB$C_BID, RMS$_NORMAL, ...) while
// every aliasing macro is spelled in lower case, so filtering by case alone
// (not by trying to detect a non-numeric value, which would still match
// some of these) cleanly separates the two without false positives.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// defineRE matches one "#define NAME value" line, capturing the name and
// the bare integer literal — deliberately anchored to upper-case names
// only (see the package doc comment above for why that's the correct, not
// merely convenient, filter).
var defineRE = regexp.MustCompile(`^#define\s+((?:FAB|RAB|RMS)\$[A-Z0-9_]+)\s+(0[Xx][0-9A-Fa-f]+|[0-9]+)\b`)

func parseDefines(src string) map[string]uint32 {
	out := map[string]uint32{}

	for _, line := range strings.Split(src, "\n") {
		m := defineRE.FindStringSubmatch(line)
		if m == nil {
			continue
		}

		v, err := strconv.ParseUint(m[2], 0, 32)
		if err != nil {
			log.Fatalf("gen: bad integer in %q: %v", line, err)
		}

		name := m[1]
		if prev, ok := out[name]; ok && prev != uint32(v) {
			log.Fatalf("gen: %s redefined with a different value (%d, then %d)", name, prev, v)
		}

		out[name] = uint32(v)
	}

	return out
}

// constantMap is one generated Go map: its variable name, the doc comment
// lines placed above it, and its entries.
type constantMap struct {
	name    string
	doc     []string
	entries map[string]uint32
}

func writeMap(b *strings.Builder, m constantMap) {
	names := make([]string, 0, len(m.entries))
	for name := range m.entries {
		names = append(names, name)
	}

	sort.Strings(names)

	for _, line := range m.doc {
		fmt.Fprintf(b, "// %s\n", line)
	}

	fmt.Fprintf(b, "var %s = map[string]uint32{\n", m.name)

	for _, name := range names {
		fmt.Fprintf(b, "\t%q: %#x,\n", name, m.entries[name])
	}

	fmt.Fprintf(b, "}\n\n")
}

func generate(maps []constantMap, sources []string) []byte {
	var b strings.Builder

	fmt.Fprintf(&b, "// Code generated by internal/vmsdef/gen from %s. DO NOT EDIT.\n",
		strings.Join(sources, ", "))
	fmt.Fprintf(&b, "package vmsdef\n\n")

	for _, m := range maps {
		writeMap(&b, m)
	}

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatalf("gen: generated source doesn't compile: %v", err)
	}

	return out
}

func main() {
	fabdef := flag.String("fabdef", "", "path to fabdef.h")
	rabdef := flag.String("rabdef", "", "path to rabdef.h")
	rmsdef := flag.String("rmsdef", "", "path to rmsdef.h")
	lnmdef := flag.String("lnmdef", "", "path to lnmdef.sdl")
	ssdef := flag.String("ssdef", "", "path to ssdef.txt")
	devdef := flag.String("devdef", "", "path to devdef.sdl")
	jpidef := flag.String("jpidef", "", "path to jpidef.sdl")
	iodef := flag.String("iodef", "", "path to iodef.sdl")
	statedef := flag.String("statedef", "", "path to statedef.txt")
	syidef := flag.String("syidef", "", "path to syidef.txt")
	dvidef := flag.String("dvidef", "", "path to dvidef.txt")
	ttdef := flag.String("ttdef", "", "path to ttdef.txt")
	prtdef := flag.String("prtdef", "", "path to prtdef.sdl")
	prvdef := flag.String("prvdef", "", "path to prvdef.txt")
	brkdef := flag.String("brkdef", "", "path to brkdef.sdl")
	fibdef := flag.String("fibdef", "", "path to fibdef.txt")
	atrdef := flag.String("atrdef", "", "path to atrdef.txt")
	sysmsg := flag.String("sysmsg", "", "path to sysmsg.txt (a message-file listing)")
	out := flag.String("out", "", "path to write the generated Go source")
	msgOut := flag.String("msgout", "", "path to write the generated message texts")
	flag.Parse()

	if *fabdef == "" || *rabdef == "" || *rmsdef == "" || *lnmdef == "" || *ssdef == "" || *devdef == "" || *jpidef == "" || *iodef == "" || *statedef == "" || *syidef == "" || *dvidef == "" || *ttdef == "" || *prtdef == "" || *prvdef == "" || *brkdef == "" || *fibdef == "" || *atrdef == "" || *sysmsg == "" || *out == "" || *msgOut == "" {
		log.Fatal("gen: -fabdef, -rabdef, -rmsdef, -lnmdef, -ssdef, -devdef, -jpidef, -iodef, -statedef, -syidef, -dvidef, -ttdef, -prtdef, -prvdef, -brkdef, -fibdef, -atrdef, -sysmsg, -out, and -msgout are all required")
	}

	constants := map[string]uint32{}

	for _, path := range []string{*fabdef, *rabdef, *rmsdef} {
		for name, v := range parseDefines(readSource(path)) {
			constants[name] = v
		}
	}

	lnm, err := parseSDL(readSource(*lnmdef))
	if err != nil {
		log.Fatalf("gen: %s: %v", *lnmdef, err)
	}

	ss, err := parseBlissLiterals(readSource(*ssdef), "SS$_")
	if err != nil {
		log.Fatalf("gen: %s: %v", *ssdef, err)
	}

	dev, err := parseSDL(readSource(*devdef))
	if err != nil {
		log.Fatalf("gen: %s: %v", *devdef, err)
	}

	jpi, err := parseSDL(readSource(*jpidef))
	if err != nil {
		log.Fatalf("gen: %s: %v", *jpidef, err)
	}

	io, err := parseSDL(readSource(*iodef))
	if err != nil {
		log.Fatalf("gen: %s: %v", *iodef, err)
	}

	state, err := parseBlissLiterals(readSource(*statedef), "SCH$C_")
	if err != nil {
		log.Fatalf("gen: %s: %v", *statedef, err)
	}

	syi, err := parseBlissLiterals(readSource(*syidef), "SYI$")
	if err != nil {
		log.Fatalf("gen: %s: %v", *syidef, err)
	}

	dvi, err := parseBlissLiterals(readSource(*dvidef), "DVI$")
	if err != nil {
		log.Fatalf("gen: %s: %v", *dvidef, err)
	}

	// "TT" takes both $TTDEF's TT$ names and its TT2$ names.
	tt, err := parseBlissLiterals(readSource(*ttdef), "TT")
	if err != nil {
		log.Fatalf("gen: %s: %v", *ttdef, err)
	}

	prt, err := parseSDL(readSource(*prtdef))
	if err != nil {
		log.Fatalf("gen: %s: %v", *prtdef, err)
	}

	prv, err := parseBlissLiterals(readSource(*prvdef), "PRV$")
	if err != nil {
		log.Fatalf("gen: %s: %v", *prvdef, err)
	}

	brk, err := parseSDL(readSource(*brkdef))
	if err != nil {
		log.Fatalf("gen: %s: %v", *brkdef, err)
	}

	fib, err := parseBlissLiterals(readSource(*fibdef), "FIB$")
	if err != nil {
		log.Fatalf("gen: %s: %v", *fibdef, err)
	}

	atr, err := parseBlissLiterals(readSource(*atrdef), "ATR$")
	if err != nil {
		log.Fatalf("gen: %s: %v", *atrdef, err)
	}

	maps := []constantMap{
		{
			name: "Constants",
			doc: []string{
				"Constants is every real FAB$/RAB$/RMS$_ symbolic-constant name",
				"(bitmask flag, named code value, or RMS$_ completion-status code)",
				"mapped to its real numeric value — what .RMSDEF (internal/asm) defines",
				"as an assembler symbol. Does not include field-offset symbols",
				"(FAB$L_STS and friends) — those come from FABFields/RABFields instead,",
				"since an offset isn't a #define-style bare header constant.",
			},
			entries: constants,
		},
		{
			name: "LNMConstants",
			doc: []string{
				"LNMConstants is every real $LNMDEF symbol: LNM$M_/LNM$V_ attribute",
				"bits, LNM$C_ limits, and LNM$_ item codes (LNM$_CHAIN is -1, stored",
				"as its 32-bit two's-complement value).",
			},
			entries: lnm,
		},
		{
			name: "SSConstants",
			doc: []string{
				"SSConstants is every real VAX/VMS $SSDEF system-service completion",
				"code (SS$_NORMAL, SS$_NOLOGNAM, ...).",
			},
			entries: ss,
		},
		{
			name: "DEVConstants",
			doc: []string{
				"DEVConstants is every real $DEVDEF device-characteristics bit:",
				"DEV$M_/DEV$V_ for the DEVCHAR longword (DEV$M_ALL, DEV$M_MNT, ...)",
				"and for DEVCHAR2 (DEV$M_CLU, ...). The two longwords are separate",
				"union members in the SDL source, so both number their bits from 0.",
			},
			entries: dev,
		},
		{
			name: "JPIConstants",
			doc: []string{
				"JPIConstants is every real $JPIDEF symbol: the JPI$_ item codes",
				"$GETJPI takes (JPI$_PID, JPI$_USERNAME, ...), JPI$K_ values such",
				"as the JPI$_MODE codes, and JPI$C_/JPI$M_ definitions.",
			},
			entries: jpi,
		},
		{
			name: "IOConstants",
			doc: []string{
				"IOConstants is every real $IODEF symbol: the IO$_ function codes",
				"$QIO takes (IO$_READVBLK, IO$_WRITEVBLK, ...) and the IO$M_/IO$V_",
				"function-modifier bits (IO$M_NOECHO, ...). The modifiers of",
				"different device classes are separate union members in the SDL",
				"source, so the same bit can have several names.",
			},
			entries: io,
		},
		{
			name: "STATEConstants",
			doc: []string{
				"STATEConstants is every real $STATEDEF scheduling-state code",
				"(SCH$C_CUR, SCH$C_HIB, ...): what $GETJPI's JPI$_STATE returns.",
			},
			entries: state,
		},
		{
			name: "SYIConstants",
			doc: []string{
				"SYIConstants is every real $SYIDEF symbol: the SYI$_ item codes",
				"$GETSYI takes (SYI$_VERSION, SYI$_NODENAME, ...) and SYI$C_ values.",
			},
			entries: syi,
		},
		{
			name: "DVIConstants",
			doc: []string{
				"DVIConstants is every real $DVIDEF symbol: the DVI$_ item codes",
				"$GETDVI takes (DVI$_DEVNAM, DVI$_DEVCLASS, ...), the DVI$M_/DVI$V_",
				"item-code flags (DVI$M_SECONDARY), and DVI$C_ values.",
			},
			entries: dvi,
		},
		{
			name: "TTConstants",
			doc: []string{
				"TTConstants is every real $TTDEF symbol: the TT$M_/TT$V_ terminal",
				"characteristics in a terminal's DEVDEPEND longword (TT$M_NOECHO,",
				"...), the TT2$M_/TT2$V_ ones in DEVDEPEND2 (TT2$M_ANSICRT, ...),",
				"and TT$C_ values such as the line speeds.",
			},
			entries: tt,
		},
		{
			name: "PRTConstants",
			doc: []string{
				"PRTConstants is every real $PRTDEF symbol: the PRT$C_ page",
				"protection codes $SETPRT takes (PRT$C_NA, PRT$C_UW, ...), in the",
				"VAX page table entry's encoding.",
			},
			entries: prt,
		},
		{
			name: "PRVConstants",
			doc: []string{
				"PRVConstants is every real $PRVDEF privilege bit number (PRV$V_CMKRNL,",
				"PRV$V_SYSNAM, ...): the privilege's bit in a quadword privilege mask,",
				"which may be past bit 31. PRV$K_NUMBER_OF_PRIVS is the count.",
			},
			entries: prv,
		},
		{
			name: "BRKConstants",
			doc: []string{
				"BRKConstants is every real $BRKDEF symbol: $BRKTHRU's send types",
				"(BRK$C_DEVICE, BRK$C_ALLUSERS, ...), its requestor classes",
				"(BRK$C_GENERAL, BRK$C_USER1, ...), and its flags (BRK$M_SCREEN, ...).",
			},
			entries: brk,
		},
		{
			name: "FIBConstants",
			doc: []string{
				"FIBConstants is every real $FIBDEF symbol: the file information",
				"block's field offsets (FIB$L_ACCTL, FIB$W_FID, FIB$W_DID, ...), its",
				"FIB$M_/FIB$V_ bits, and FIB$C_ codes: the disk ACP's $QIO argument.",
			},
			entries: fib,
		},
		{
			name: "ATRConstants",
			doc: []string{
				"ATRConstants is every real $ATRDEF symbol: the disk ACP's attribute",
				"codes (ATR$C_RECATTR, ATR$C_UCHAR, ...), their sizes (ATR$S_), and the",
				"layout of an attribute list's entries (ATR$W_SIZE, ATR$W_TYPE, ATR$L_ADDR).",
			},
			entries: atr,
		},
	}

	sources := []string{*fabdef, *rabdef, *rmsdef, *lnmdef, *ssdef, *devdef, *jpidef, *iodef, *statedef, *syidef, *dvidef, *ttdef, *prtdef, *prvdef, *brkdef, *fibdef, *atrdef}
	code := generate(maps, sources)

	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatalf("gen: %v", err)
	}

	fmt.Fprintf(os.Stderr, "gen: wrote %d/%d/%d/%d/%d/%d/%d/%d/%d/%d/%d/%d/%d/%d/%d constants to %s\n", len(constants), len(lnm), len(ss), len(dev), len(jpi), len(io), len(state), len(syi), len(dvi), len(tt), len(prt), len(prv), len(brk), len(fib), len(atr), *out)

	// The message texts go in a file of their own (see msg.go).
	msgs, facilities, err := parseMessages(readSource(*sysmsg))
	if err != nil {
		log.Fatalf("gen: %s: %v", *sysmsg, err)
	}

	if err := os.WriteFile(*msgOut, generateMessages(msgs, facilities, *sysmsg), 0o644); err != nil {
		log.Fatalf("gen: %v", err)
	}

	fmt.Fprintf(os.Stderr, "gen: wrote %d messages in %d facilities to %s\n", len(msgs), len(facilities), *msgOut)
}

func readSource(path string) string {
	src, err := os.ReadFile(path)
	if err != nil {
		log.Fatalf("gen: %v", err)
	}

	return string(src)
}
